"""Environment checks: ``l4d1ctl doctor``.

Every check is cheap, read-only, and prints an actionable next step. The intent
is that a bug report can start with the doctor output instead of "it crashes".
"""

from __future__ import annotations

import shutil
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import List, Optional, Sequence

from . import depot, gameinfo, gamemod, mods, steamid, steamlib
from .paths import PortPaths


@dataclass
class Result:
    level: str  # ok | warn | fail
    label: str
    detail: str = ""

    def line(self) -> str:
        tag = {"ok": "PASS", "warn": "WARN", "fail": "FAIL"}[self.level]
        suffix = f"  ({self.detail})" if self.detail else ""
        return f"[{tag}] {self.label}{suffix}"


def _which(names: Sequence[str]) -> Optional[str]:
    for name in names:
        found = shutil.which(name)
        if found:
            return found
    return None


def run(paths: PortPaths, *, steam_root: Optional[str] = None,
        check_network: bool = False) -> List[Result]:
    results: List[Result] = []

    python_ok = sys.version_info >= (3, 8)
    results.append(Result("ok" if python_ok else "fail", f"Python {sys.version.split()[0]}",
                          "" if python_ok else "3.8 or newer is required"))

    # -- Steam ------------------------------------------------------------
    root = steamlib.find_steam_root(steam_root)
    if root:
        results.append(Result("ok", "Steam install found", str(root)))
        libraries = steamlib.library_folders(root)
        results.append(Result("ok", f"{len(libraries)} Steam librar(y/ies)"))

        install = steamlib.find_install(500, libraries)
        if install:
            state = "complete" if install.looks_complete else "incomplete"
            results.append(Result("ok" if install.looks_complete else "warn",
                                  f"Left 4 Dead install ({state})", str(install.install_dir)))
        else:
            results.append(Result("warn", "Left 4 Dead (appid 500) not found in any library",
                                  "install it with Steam, or use `l4d1ctl import`"))
        user = steamlib.current_user(root)
        if user:
            results.append(Result("ok", f"local account: {user.display_name}",
                                  steamid.to_steam3(user.steamid64)))
        else:
            results.append(Result("warn", "no local Steam account in config/loginusers.vdf"))
    else:
        results.append(Result("warn", "no Steam install found",
                              "set L4D1_STEAM_ROOT, or import content made elsewhere"))

    # -- content ----------------------------------------------------------
    verification = depot.verify_game_dir(paths.gamedir)
    for check in verification.checks:
        level = {"ok": "ok", "warn": "warn", "fail": "fail"}[check.level]
        results.append(Result(level, check.message))
    results.append(Result("ok" if verification.ok else "fail",
                          f"game content: {verification.summary()}"))

    # -- gameinfo ---------------------------------------------------------
    for problem in gameinfo.check(paths):
        results.append(Result("warn" if "mods" in problem else "fail", f"gameinfo.txt: {problem}"))
    if gameinfo.is_generated(paths.gameinfo):
        results.append(Result("ok", "gameinfo.txt is generated by l4d1ctl"))

    # -- mods -------------------------------------------------------------
    manager = mods.ModManager(paths)
    known = manager.scan()
    enabled = [m for m in known if m.enabled]
    results.append(Result("ok" if known else "warn", f"{len(known)} mod(s), {len(enabled)} enabled"))
    for issue in manager.validate():
        results.append(Result("fail" if issue.level == "fail" else "warn", f"mods: {issue.message}"))

    # -- identity ---------------------------------------------------------
    identity = steamlib.Identity.from_file(paths.identity_json)
    if identity:
        results.append(Result("ok", f"identity: {identity.display_name}", str(identity.steamid64)))
        if identity.avatar_path and Path(identity.avatar_path).is_file():
            results.append(Result("ok", "avatar cached", identity.avatar_path))
        else:
            results.append(Result("warn", "no cached avatar",
                                  "run `l4d1ctl identity --avatar` with a Web API key"))
    else:
        results.append(Result("warn", "no identity yet", "run `l4d1ctl identity`"))

    # -- providers --------------------------------------------------------
    steamcmd = _which(("steamcmd", "steamcmd.sh"))
    if steamcmd:
        results.append(Result("ok", "steamcmd available", steamcmd))
    else:
        results.append(Result("warn", "steamcmd not on PATH",
                              "only needed for `l4d1ctl fetch --provider steamcmd`"))
    depotdownloader = _which(("DepotDownloader", "depotdownloader"))
    if depotdownloader:
        results.append(Result("ok", "DepotDownloader available", depotdownloader))

    # -- game module ------------------------------------------------------
    module_status = gamemod.status(paths)
    if module_status.ok:
        names = ", ".join(f"{n} ({m.info.summary})" for n, m in sorted(module_status.modules.items()))
        results.append(Result("ok", "game module installed", names))
    else:
        results.append(Result("warn", "no complete game module in " + str(module_status.bindir),
                              "run `l4d1ctl module install --from <build>/bin`"))
    for warning in module_status.warnings:
        if module_status.ok:
            results.append(Result("warn", f"game module: {warning}"))

    # -- engine -----------------------------------------------------------
    engine_candidates = [
        paths.gamedir.parent / "hl2_linux",
        paths.gamedir.parent / "bin" / "launcher.so",
        paths.gamedir.parent / "liblauncher.so",
    ]
    found_engine = [str(p) for p in engine_candidates if p.exists()]
    if found_engine:
        results.append(Result("ok", "engine build artifacts present", ", ".join(found_engine)))
    else:
        results.append(Result("warn", "no engine binary next to the game dir",
                              "build with ./waf build, or copy the port's libs to the same folder"))

    return results


def exit_code(results: Sequence[Result]) -> int:
    if any(r.level == "fail" for r in results):
        return 2
    if any(r.level == "warn" for r in results):
        return 1
    return 0


__all__ = ["Result", "exit_code", "run"]

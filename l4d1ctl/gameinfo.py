"""Generation of a port-friendly ``left4dead/gameinfo.txt``.

The retail gameinfo.txt that ships inside the depot is written for Valve's own
engine build: it lists Steam-specific paths and, on some branches, paths that
only exist in a full Steam install. We keep a generated file instead, with two
goals:

* mount the game directory plus every enabled mod (``mods/enabled/*``)
* keep everything else (appid, title, type) recognisable to the engine and to
  the UI

The generated file is marked with a comment and a state file next to it, so
``l4d1ctl init`` never silently overwrites a hand-edited gameinfo.
"""

from __future__ import annotations

import hashlib
from dataclasses import dataclass
from pathlib import Path
from typing import List, Optional, Sequence

from .paths import APPID, PortPaths

GENERATED_MARKER = "// Generated by l4d1ctl - edits will be lost on `l4d1ctl init --force`"
MODS_SEARCH_PATH = "mods/enabled/*"


@dataclass
class GameInfoSpec:
    title: str = "Left 4 Dead"
    internal_title: str = "LEFT 4 DEAD"
    appid: int = APPID
    game_type: str = "multiplayer_only"
    mount_mods: bool = True
    mount_platform: bool = True
    extra_game_paths: Sequence[str] = ()
    extra_options: Sequence[str] = ("nomodels 1", "nohimodel 1", "nocrosshair 0")


def render(spec: Optional[GameInfoSpec] = None) -> str:
    spec = spec or GameInfoSpec()
    lines: List[str] = [
        GENERATED_MARKER,
        '"GameInfo"',
        "{",
        f'\tgame\t\t"{spec.title}"',
        f'\ttitle\t\t"{spec.internal_title}"',
        f'\ttype\t\t{spec.game_type}',
    ]
    for option in spec.extra_options:
        lines.append(f"\t{option}")

    lines.extend(
        [
            "\tFileSystem",
            "\t{",
            f"\t\tSteamAppId\t\t{spec.appid}",
            "\t\tSearchPaths",
            "\t\t{",
            "\t\t\tGame\t|gameinfo_path|.",
        ]
    )
    for path in spec.extra_game_paths:
        lines.append(f"\t\t\tGame\t|gameinfo_path|{path}")
    if spec.mount_mods:
        # Wildcards are expanded by FileSystem_AddLoadedSearchPath: every folder
        # and every *_dir.vpk below mods/enabled gets mounted, alphabetically.
        lines.append(f"\t\t\tGame\t|gameinfo_path|{MODS_SEARCH_PATH}")
    if spec.mount_platform:
        lines.append("\t\t\tPlatform\t|all_source_engine_paths|platform")
    lines.extend(["\t\t}", "\t}", "}", ""])
    return "\n".join(lines)


def _digest(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def is_generated(path: Path) -> bool:
    path = Path(path)
    try:
        with path.open("r", encoding="utf-8", errors="replace") as handle:
            first = handle.readline()
    except OSError:
        return False
    return first.strip().startswith("// Generated by l4d1ctl")


@dataclass
class WriteResult:
    path: Path
    written: bool
    reason: dict


def write(paths: PortPaths, spec: Optional[GameInfoSpec] = None, *,
          force: bool = False, dry_run: bool = False) -> WriteResult:
    """Write gameinfo.txt, refusing to clobber a file we did not generate."""
    spec = spec or GameInfoSpec()
    text = render(spec)
    target = paths.gameinfo

    if target.exists() and not force and not is_generated(target):
        return WriteResult(target, False, {
            "error": "existing gameinfo.txt was not generated by l4d1ctl; pass --force to replace it",
        })

    if target.exists() and not force and is_generated(target):
        if target.read_text(encoding="utf-8", errors="replace") == text:
            if not dry_run:
                paths.ensure_state()
                paths.gameinfo_marker.write_text(_digest(text) + "\n", encoding="utf-8")
            return WriteResult(target, False, {"unchanged": True})

    if not dry_run:
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(text, encoding="utf-8")
        paths.ensure_state()
        paths.gameinfo_marker.write_text(_digest(text) + "\n", encoding="utf-8")
    return WriteResult(target, True, {"bytes": len(text)})


def check(paths: PortPaths) -> List[str]:
    """Human-readable checks used by ``doctor``."""
    problems: List[str] = []
    if not paths.gameinfo.is_file():
        return ["gameinfo.txt missing"]
    text = paths.gameinfo.read_text(encoding="utf-8", errors="replace")
    if "SearchPaths" not in text:
        problems.append("gameinfo.txt has no SearchPaths block")
    if MODS_SEARCH_PATH not in text:
        problems.append(f"gameinfo.txt does not mount {MODS_SEARCH_PATH}; mods will not load")
    if '"GameInfo"' not in text:
        problems.append("gameinfo.txt has no GameInfo root")
    return problems



import tempfile
import unittest
from pathlib import Path

from l4d1ctl import gameinfo, kv, launch, steamlib
from l4d1ctl.paths import PortPaths


def make_paths(root: Path) -> PortPaths:
    return PortPaths(root / "left4dead")


class GameInfoTests(unittest.TestCase):
    def test_render_contains_mount_and_appid(self):
        text = gameinfo.render()
        self.assertIn('"GameInfo"', text)
        self.assertIn("SteamAppId", text)
        self.assertIn("500", text)
        self.assertIn(gameinfo.MODS_SEARCH_PATH, text)
        # It must parse as KeyValues, otherwise the engine will refuse it.
        nodes = kv.loads(text)
        root = kv.find(nodes, "GameInfo")
        self.assertIsNotNone(root)
        self.assertEqual(root.get("game"), "Left 4 Dead")
        search = root.find("filesystem").find("searchpaths")
        self.assertTrue(any(gameinfo.MODS_SEARCH_PATH in (c.value or "") for c in search.children))

    def test_render_options(self):
        spec = gameinfo.GameInfoSpec(mount_mods=False, mount_platform=False, appid=500,
                                     extra_game_paths=("custom",))
        text = gameinfo.render(spec)
        self.assertNotIn(gameinfo.MODS_SEARCH_PATH, text)
        self.assertNotIn("platform", text)
        self.assertIn("|gameinfo_path|custom", text)

    def test_write_and_marker(self):
        with tempfile.TemporaryDirectory() as tmp:
            paths = make_paths(Path(tmp))
            paths.gamedir.mkdir(parents=True)
            result = gameinfo.write(paths)
            self.assertTrue(result.written)
            self.assertTrue(gameinfo.is_generated(paths.gameinfo))
            self.assertTrue(paths.gameinfo_marker.is_file())
            again = gameinfo.write(paths)
            self.assertFalse(again.written)
            self.assertTrue(again.reason.get("unchanged"))

    def test_refuses_to_clobber_user_file(self):
        with tempfile.TemporaryDirectory() as tmp:
            paths = make_paths(Path(tmp))
            paths.gamedir.mkdir(parents=True)
            paths.gameinfo.write_text('"GameInfo" { game "retail" }', encoding="utf-8")
            result = gameinfo.write(paths)
            self.assertFalse(result.written)
            self.assertIn("error", result.reason)
            self.assertIn("retail", paths.gameinfo.read_text(encoding="utf-8"))

            forced = gameinfo.write(paths, force=True)
            self.assertTrue(forced.written)
            self.assertIn("Generated by l4d1ctl", paths.gameinfo.read_text(encoding="utf-8"))

    def test_check(self):
        with tempfile.TemporaryDirectory() as tmp:
            paths = make_paths(Path(tmp))
            self.assertEqual(gameinfo.check(paths), ["gameinfo.txt missing"])
            paths.gamedir.mkdir(parents=True)
            paths.gameinfo.write_text('"GameInfo" { }', encoding="utf-8")
            problems = gameinfo.check(paths)
            self.assertTrue(any("SearchPaths" in p for p in problems))
            gameinfo.write(paths, force=True)
            self.assertEqual(gameinfo.check(paths), [])


class LaunchTests(unittest.TestCase):
    def test_identity_cfg_escaping(self):
        identity = steamlib.Identity(steamid64=76561198000000001, persona_name='He said "hi"')
        text = launch.identity_cfg_text(identity)
        self.assertIn('name "He said \\"hi\\""', text)
        self.assertIn("76561198000000001", text)

    def test_identity_cfg_without_identity(self):
        text = launch.identity_cfg_text(None)
        self.assertIn("no identity", text)
        self.assertNotIn("name ", text)

    def test_build_plan(self):
        with tempfile.TemporaryDirectory() as tmp:
            paths = make_paths(Path(tmp))
            identity = steamlib.Identity(steamid64=76561198000000001, persona_name="Zoey Fan")
            plan = launch.build_launch_plan(paths, identity=identity, map_name="c1m1_hotel")
            self.assertEqual(plan.argv[0], launch.DEFAULT_ENGINE)
            self.assertIn("-game", plan.argv)
            self.assertEqual(plan.argv[plan.argv.index("-game") + 1], "left4dead")
            self.assertIn("-nosteam", plan.argv)
            self.assertIn("-insecure", plan.argv)
            self.assertIn("-fullscreen", plan.argv)
            self.assertEqual(plan.argv[-2:], ["+map", "c1m1_hotel"])
            self.assertIn("+exec", plan.argv)
            self.assertTrue(plan.cfg_written.is_file())
            self.assertEqual(plan.env["L4D1_STEAMID64"], "76561198000000001")
            self.assertIn('name "Zoey Fan"', plan.cfg_written.read_text(encoding="utf-8"))

    def test_build_plan_windowed_no_identity(self):
        with tempfile.TemporaryDirectory() as tmp:
            paths = make_paths(Path(tmp))
            plan = launch.build_launch_plan(paths, identity=None, fullscreen=False,
                                            write_cfg=False, dry_run=True)
            self.assertIn("-windowed", plan.argv)
            self.assertNotIn("-fullscreen", plan.argv)
            self.assertTrue(plan.warnings)
            self.assertIsNone(plan.cfg_written)

    def test_extra_args_are_kept_once(self):
        with tempfile.TemporaryDirectory() as tmp:
            paths = make_paths(Path(tmp))
            plan = launch.build_launch_plan(paths, extra_args=("-novid", "-dev"), write_cfg=False)
            self.assertEqual(plan.argv.count("-novid"), 1)
            self.assertIn("-dev", plan.argv)

    def test_exec_still_listed_when_printing(self):
        with tempfile.TemporaryDirectory() as tmp:
            paths = make_paths(Path(tmp))
            # `identity` already wrote the cfg; `launch --print` must still show it.
            paths.cfg_dir.mkdir(parents=True)
            paths.identity_cfg.write_text('name "x"', encoding="utf-8")
            plan = launch.build_launch_plan(paths, write_cfg=False, dry_run=True)
            self.assertIn("+exec", plan.argv)
            self.assertEqual(plan.argv[plan.argv.index("+exec") + 1], launch.IDENTITY_CFG_NAME)

    def test_command_quoting(self):
        with tempfile.TemporaryDirectory() as tmp:
            paths = make_paths(Path(tmp))
            plan = launch.build_launch_plan(paths, extra_args=("+connect", "a b"), write_cfg=False)
            self.assertIn("'a b'", plan.command())


if __name__ == "__main__":
    unittest.main()

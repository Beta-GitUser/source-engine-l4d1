"""Launch planning: argv, environment, and the generated identity config.

The Android launcher (``launcher/android/main.cpp``) historically hardcoded

    -fullscreen -nosteam -insecure -nouserclip

That is fine for half-life 2 but wrong for a port that wants to carry a player
name and per-user settings. This module mirrors what ``launcher/portcore`` does
in C++ so the two can be kept in sync: the Python side is the reference, the
C++ side is what actually runs on the phone.
"""

from __future__ import annotations

import shlex
from dataclasses import dataclass, field
from pathlib import Path
from typing import Dict, List, Optional, Sequence

from .paths import PortPaths
from .steamlib import Identity

DEFAULT_ENGINE = "hl2_linux"
IDENTITY_CFG_NAME = "l4d1_identity.cfg"

# Deliberately boring defaults. Nothing here requires Steam, and nothing here
# pretends to be a retail L4D1 client on Valve's network.
DEFAULT_EXTRA_ARGS: Sequence[str] = ("-novid", "-console", "-nouserclip")


@dataclass
class LaunchPlan:
    argv: List[str]
    env: Dict[str, str] = field(default_factory=dict)
    cfg_written: Optional[Path] = None
    warnings: List[str] = field(default_factory=list)

    def command(self) -> str:
        return " ".join(shlex.quote(part) for part in self.argv)


def identity_cfg_text(identity: Optional[Identity], extra_commands: Sequence[str] = ()) -> str:
    lines = ["// Generated by l4d1ctl - regenerated on every launch.", "// Offline identity only: no Steam logon happens."]
    if identity is not None:
        lines.append(f'name "{_escape(identity.display_name)}"')
        lines.append(f"// SteamID64: {identity.steamid64}")
    else:
        lines.append("// no identity resolved yet - run `l4d1ctl identity`")
    for command in extra_commands:
        lines.append(command)
    lines.append("")
    return "\n".join(lines)


def _escape(value: str) -> str:
    return value.replace("\\", "\\\\").replace('"', '\\"')


def write_identity_cfg(paths: PortPaths, identity: Optional[Identity], *,
                       extra_commands: Sequence[str] = (),
                       dry_run: bool = False) -> Path:
    text = identity_cfg_text(identity, extra_commands)
    target = paths.cfg_dir / IDENTITY_CFG_NAME
    if not dry_run:
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(text, encoding="utf-8")
    return target


def build_launch_plan(
    paths: PortPaths,
    *,
    engine: str = DEFAULT_ENGINE,
    identity: Optional[Identity] = None,
    map_name: Optional[str] = None,
    extra_args: Sequence[str] = (),
    fullscreen: bool = True,
    nosteam: bool = True,
    insecure: bool = True,
    touch: bool = True,
    write_cfg: bool = True,
    dry_run: bool = False,
) -> LaunchPlan:
    argv: List[str] = [engine]
    warnings: List[str] = []

    for arg in DEFAULT_EXTRA_ARGS:
        if arg not in extra_args:
            argv.append(arg)
    argv.extend(extra_args)

    argv.extend(["-game", paths.gamedir.name])
    argv.append("-fullscreen" if fullscreen else "-windowed")
    if touch:
        argv.append("-touch")
    if nosteam:
        # The engine's own fallback path: no Steam logon, achievements handled
        # locally, server browser still works.
        argv.append("-nosteam")
    if insecure:
        argv.append("-insecure")

    cfg_written = None
    if write_cfg:
        cfg_written = write_identity_cfg(paths, identity, dry_run=dry_run)
    # The cfg is produced by `identity` and re-written on a real launch; include
    # the exec either way so `launch --print` shows what the engine will run.
    if write_cfg or paths.identity_cfg.is_file():
        argv.extend(["+exec", IDENTITY_CFG_NAME])

    if map_name:
        argv.extend(["+map", map_name])

    env = {
        "L4D1_GAMEDIR": str(paths.gamedir),
    }
    if identity is not None:
        env["L4D1_STEAMID64"] = str(identity.steamid64)
        env["L4D1_PLAYER_NAME"] = identity.display_name
    else:
        warnings.append("no identity: the game will show the default player name")

    return LaunchPlan(argv=argv, env=env, cfg_written=cfg_written, warnings=warnings)


__all__ = [
    "DEFAULT_ENGINE",
    "IDENTITY_CFG_NAME",
    "LaunchPlan",
    "build_launch_plan",
    "identity_cfg_text",
    "write_identity_cfg",
]
